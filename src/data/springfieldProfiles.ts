import type { ArchitectProfile, ProfileMark, SelectedProject } from "@/data/architectProfiles";

const GUIDE = { label: "Springfield, Missouri", path: "/d/architects/springfield-missouri" };
const CHECKED = "8 November 2026";

function mark(name: string, file: string, sourceUrl: string): ProfileMark {
  return {
    src: `/directory-marks/${file}`,
    alt: "",
    author: name,
    license: "Official identifying mark",
    licenseUrl: sourceUrl,
    sourceUrl,
    attribution: `${name} mark, from the practice website`,
    permissionStatus: "official-identifying-mark",
    caveat: "The mark is the practice's own logo, shown small to identify the firm. It is not a Creative Commons image, and it does not imply endorsement.",
  };
}

function project(entry: {
  name: string;
  city: string;
  country?: string;
  status: string;
  use: string;
  summary: string;
  sourceUrl: string;
  sourceLabel: string;
}): SelectedProject {
  return {
    name: entry.name,
    city: entry.city,
    country: entry.country ?? "United States",
    year: "",
    status: entry.status,
    use: entry.use,
    client: null,
    collaborators: null,
    projectPath: null,
    sourceUrl: entry.sourceUrl,
    sourceLabel: entry.sourceLabel,
    image: null,
    summary: entry.summary,
  };
}

function sourcesNote(hasMark: boolean, registration: string) {
  const markLine = hasMark
    ? "The mark beside the name is the practice's own logo, shown small to identify the firm. It is not a Creative Commons image, and it does not imply endorsement."
    : "The name is set in type. An official mark is not shown.";
  return `Checked ${CHECKED}. ${markLine} ${registration} Project photographs are not shown.`.replace(/\s+/g, " ").trim();
}

function registeredArchitect(displayName: string, number: string, expires: string) {
  return {
    place: "Named architect",
    status: `Missouri registered architect: ${displayName}, no. ${number}`,
    note: `Springfield. Expires ${expires}.`,
  };
}

const firmUnverified = () => ({
  place: "Firm certificate of authority",
  status: "Not verified",
  note: "Separate from the individual architect record.",
});

function registerSource(record: string, extra = "Firm certificate of authority: not verified.") {
  return `Missouri licensee search, Active Licensee Only, 8 November 2026: ${record} The detail page does not label the record Active. ${extra}`;
}

